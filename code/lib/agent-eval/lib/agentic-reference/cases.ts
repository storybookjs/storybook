/** Experiment names the generated stubs (and results directories) carry. */
export function knownExperimentNames(): string[] {
  return AGENTIC_REF_CASES.map(
    (agenticRefCase) => `${EXPERIMENT_NAME_PREFIX}${agenticRefCase.name}`
  );
}

// Duplicate names would make agenticRefCaseExperiment always pick the first
// match and collide generated stubs, results directories, and fingerprints.
const caseNames = AGENTIC_REF_CASES.map((agenticRefCase) => agenticRefCase.name);
const duplicateNames = [...new Set(caseNames.filter((name, i) => caseNames.indexOf(name) !== i))];
if (duplicateNames.length > 0) {
  throw new Error(`AGENTIC_REF_CASES: duplicate case names: ${duplicateNames.join(', ')}`);
}

// Two cases sharing a derived shortName would be indistinguishable in
// results:compare's CSV/manifest output — commands.ts, cells.ts, and the
// stats stage all key on shortName, so a collision would silently conflate
// two different experiments under one label.
const shortNamesByCase = new Map(caseNames.map((name) => [name, shortNameOf(name)]));
const shortNameCollisions = [...new Set(shortNamesByCase.values())]
  .map((shortName) => caseNames.filter((name) => shortNamesByCase.get(name) === shortName))
  .filter((group) => group.length > 1);
if (shortNameCollisions.length > 0) {
  throw new Error(
    `AGENTIC_REF_CASES: cases share a derived short name: ${shortNameCollisions.map((group) => group.join(', ')).join('; ')}`
  );
}

// AGENTIC_REF_EVALS=<eval>[,<eval>] narrows every case's supported workflow evals
// to the ones matching the environment variable. This is a filtering mechanism
// rather than an overriding one.
function applyEvalSelection(evals: string[]): string[] {
  const raw = process.env.AGENTIC_REF_EVALS;
  if (raw === undefined || raw === '') {
    return evals;
  }
  const tokens = raw
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean);
  if (tokens.length === 0) {
    throw new Error(
      `AGENTIC_REF_EVALS: no workflow names in "${raw}". Valid: ${AGENTIC_REF_EVAL_REGISTRY.join(', ')}`
    );
  }

  const wanted = resolveEvalSelection(tokens, AGENTIC_REF_EVAL_REGISTRY);
  return evals.filter((name) => wanted.includes(name));
}

const EVALS_DIR = fileURLToPath(new URL('../../evals', import.meta.url));

// Config-load guard against the runner's most expensive failure mode: its
// eval-name resolution falls back to EVERY fixture when a configured name
// matches nothing, so a typo here would otherwise run the full eval set on a
// paid experiment.
function assertEvalsExist(caseName: string, evals: string[]): string[] {
  const missing = evals.filter((evalName) => !existsSync(join(EVALS_DIR, evalName)));
  if (missing.length > 0) {
    throw new Error(
      `agenticRefCaseExperiment: case "${caseName}" references evals with no fixture directory: ${missing.join(', ')}`
    );
  }
  return evals;
}

/** Look up a case by name and build its ExperimentConfig. */
export function agenticRefCaseExperiment(name: string): ExperimentConfig {
  const agenticRefCase = AGENTIC_REF_CASES.find((candidate) => candidate.name === name);
  if (agenticRefCase === undefined) {
    const known = AGENTIC_REF_CASES.map((candidate) => candidate.name).join(', ');
    throw new Error(`agenticRefCaseExperiment: unknown case "${name}". Known cases: ${known}`);
  }

  return agenticRefExperiment({
    name: agenticRefCase.name,
    evals: assertEvalsExist(
      name,
      applyEvalSelection(agenticRefCase.evals ?? AGENTIC_REF_EVAL_REGISTRY)
    ),
    agent: agenticRefCase.agent,
    storybookMcpUrl: agenticRefCase.storybookMcpUrl,
    storybookMcpPackage: agenticRefCase.storybookMcpPackage,
    integration: agenticRefCase.integration,
    mcpServers: agenticRefCase.mcpServers,
    skillDirs: agenticRefCase.skillDirs,
    editPrompt: agenticRefCase.editPrompt,
    overrides: agenticRefCase.overrides,
  });
}
