#!/usr/bin/env node
// Rebuilds agent-eval/.agentic-ref/ — a throwaway, gitignored work directory —
// from lib/agentic-reference/cases.ts. The experiments/ subdirectory is fully
// owned by this generator: stale stub files are deleted and changed ones
// rewritten on every run. evals/ and results/ are relative symlinks into the
// shared agent-eval directories, so the agent-eval CLI — which resolves
// experiments/, evals/, results/ from process.cwd() — can run entirely from
// inside .agentic-ref/.
//
// Usage: node scripts/generate-agentic-ref-experiments.ts

import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { pathToFileURL } from 'node:url';

import { AGENTIC_REF_CASES } from '../lib/agentic-reference/cases.ts';
import {
  AGENT_EVAL_ROOT,
  EXPERIMENT_STUB_PATTERN,
  EXPERIMENTS_DIR,
  GENERATED_EVALS_WORK_DIR,
} from '#lib/agentic-reference/constants';

function experimentFileName(caseName: string): string {
  return `agentic-ref-${caseName}.ts`;
}

function renderExperimentStub(caseName: string): string {
  return `// Generated by scripts/generate-agentic-ref-experiments.ts — edit lib/agentic-reference/cases.ts, then regenerate.
import { agenticRefCaseExperiment } from '../../lib/agentic-reference/cases.ts';

export default agenticRefCaseExperiment('${caseName}');
`;
}

// The CLI resolves evals/ and results/ from cwd, but both must stay shared
// with the real agent-eval directories — symlinks give the workdir a complete
// project shape without copying; relative so the repo can move.
function ensureRelativeSymlink(linkPath: string, targetDir: string): void {
  const target = relative(dirname(linkPath), targetDir);

  // lstat rather than exists: a dangling symlink reports as non-existent but
  // still blocks symlinkSync.
  let existing: ReturnType<typeof lstatSync> | undefined;
  try {
    existing = lstatSync(linkPath);
  } catch {}

  if (existing !== undefined) {
    if (existing.isSymbolicLink() && readlinkSync(linkPath) === target) {
      return;
    }
    rmSync(linkPath, { recursive: true, force: true });
  }

  symlinkSync(target, linkPath);
}

export function generateAgenticRefWorkdir(): void {
  mkdirSync(EXPERIMENTS_DIR, { recursive: true });
  // The results symlink would dangle without this — created here rather than
  // left to agent-eval, since the generator runs before the CLI does.
  mkdirSync(join(AGENT_EVAL_ROOT, 'results'), { recursive: true });

  const expectedByName = new Map(
    AGENTIC_REF_CASES.map((agenticRefCase) => [
      experimentFileName(agenticRefCase.name),
      agenticRefCase.name,
    ])
  );
  const existingNames = new Set(
    readdirSync(EXPERIMENTS_DIR).filter((name) => EXPERIMENT_STUB_PATTERN.test(name))
  );

  let written = 0;
  let unchanged = 0;
  let removed = 0;

  for (const [fileName, caseName] of expectedByName) {
    const filePath = join(EXPERIMENTS_DIR, fileName);
    const content = renderExperimentStub(caseName);

    if (existingNames.has(fileName) && readFileSync(filePath, 'utf8') === content) {
      unchanged++;
      continue;
    }

    writeFileSync(filePath, content);
    written++;
  }

  for (const fileName of existingNames) {
    if (expectedByName.has(fileName)) {
      continue;
    }
    rmSync(join(EXPERIMENTS_DIR, fileName));
    removed++;
  }

  ensureRelativeSymlink(join(GENERATED_EVALS_WORK_DIR, 'evals'), join(AGENT_EVAL_ROOT, 'evals'));
  ensureRelativeSymlink(
    join(GENERATED_EVALS_WORK_DIR, 'results'),
    join(AGENT_EVAL_ROOT, 'results')
  );

  // The agent-eval CLI loads .env.local and .env from process.cwd(), which is
  // this work directory when running agentic-ref evals — without these links a
  // local run silently skips every experiment for missing API keys.
  for (const envFile of ['.env', '.env.local']) {
    if (existsSync(join(AGENT_EVAL_ROOT, envFile))) {
      ensureRelativeSymlink(
        join(GENERATED_EVALS_WORK_DIR, envFile),
        join(AGENT_EVAL_ROOT, envFile)
      );
    }
  }

  console.log(
    `generate-agentic-ref-experiments: ${written} written, ${unchanged} unchanged, ${removed} removed.`
  );
}

// Also importable: scripts/run-agentic-ref.ts regenerates the work directory
// in-process before handing off to the CLI.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generateAgenticRefWorkdir();
}
