import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';

import * as esbuild from 'esbuild';
import { dirname, join } from 'pathe';
import { expect, it } from 'vitest';

import { preserveManagerEntrySideEffectsPlugin } from './managerEntrySideEffects.ts';

/*
 * Builds a fixture project shaped like a real manager entry setup: an addon package that declares
 * `"sideEffects": false` and registers its panel through an internal import one level below its
 * manager entry, plus a side-effect-free dependency (a @storybook/icons stand-in). The entry is
 * imported through a wrapper file, as generated by `wrapManagerEntries` (`import '<entry>';`).
 *
 * Assertions run against the emitted bundle text: `register.js` and the icons dependency have no
 * exports, so their top-level `globalThis` assignments are the proof they survived tree-shaking.
 */
const createFixtureProject = async () => {
  const root = await mkdtemp(join(tmpdir(), 'sb-manager-entry-side-effects-'));

  const addonDistDir = join(root, 'node_modules', 'fixture-addon', 'dist');
  await mkdir(addonDistDir, { recursive: true });
  await writeFile(
    join(root, 'node_modules', 'fixture-addon', 'package.json'),
    JSON.stringify({
      name: 'fixture-addon',
      version: '1.0.0',
      type: 'module',
      sideEffects: false,
      exports: { '.': './dist/manager.js' },
    })
  );
  await writeFile(
    join(addonDistDir, 'manager.js'),
    "import './register.js';\nimport 'fixture-icons';\n"
  );
  await writeFile(
    join(addonDistDir, 'register.js'),
    'globalThis.__FIXTURE_PANEL_REGISTERED__ = true;\n'
  );

  const iconsDistDir = join(root, 'node_modules', 'fixture-icons', 'dist');
  await mkdir(iconsDistDir, { recursive: true });
  await writeFile(
    join(root, 'node_modules', 'fixture-icons', 'package.json'),
    JSON.stringify({
      name: 'fixture-icons',
      version: '1.0.0',
      type: 'module',
      sideEffects: false,
      main: './dist/index.js',
    })
  );
  await writeFile(
    join(iconsDistDir, 'index.js'),
    'globalThis.__FIXTURE_ICON_SIDE_EFFECT__ = true;\nexport const Icon = () => null;\n'
  );

  return root;
};

const writeWrapper = async (root: string, specifier: string) => {
  const wrapperPath = join(root, 'sb-addons', 'wrapper.js');
  await mkdir(dirname(wrapperPath), { recursive: true });
  await writeFile(wrapperPath, `import '${specifier.replaceAll("'", "\\'")}';\n`);
  return wrapperPath;
};

const buildManagerBundle = async (root: string, wrapperPath: string, withPlugin: boolean) => {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: [wrapperPath],
    bundle: true,
    write: false,
    outdir: 'dist',
    platform: 'browser',
    format: 'iife',
    plugins: withPlugin ? [preserveManagerEntrySideEffectsPlugin([wrapperPath])] : [],
  });
  return result.outputFiles[0].text;
};

it('keeps an addon registration one import below a bare-specifier entry', async () => {
  const root = await createFixtureProject();
  const wrapperPath = await writeWrapper(root, 'fixture-addon');
  const bundle = await buildManagerBundle(root, wrapperPath, true);

  expect(bundle).toContain('__FIXTURE_PANEL_REGISTERED__');
});

it('keeps an addon registration when the entry is an absolute path', async () => {
  const root = await createFixtureProject();
  const managerPath = join(root, 'node_modules', 'fixture-addon', 'dist', 'manager.js');
  const wrapperPath = await writeWrapper(root, managerPath);
  const bundle = await buildManagerBundle(root, wrapperPath, true);

  expect(bundle).toContain('__FIXTURE_PANEL_REGISTERED__');
});

it('keeps tree-shaking of side-effect-free dependencies imported by the entry', async () => {
  const root = await createFixtureProject();
  const wrapperPath = await writeWrapper(root, 'fixture-addon');
  const bundle = await buildManagerBundle(root, wrapperPath, true);

  expect(bundle).not.toContain('__FIXTURE_ICON_SIDE_EFFECT__');
});

it('without the plugin, the entry import and its registration are dropped', async () => {
  const root = await createFixtureProject();
  const wrapperPath = await writeWrapper(root, 'fixture-addon');
  const bundle = await buildManagerBundle(root, wrapperPath, false);

  expect(bundle).not.toContain('__FIXTURE_PANEL_REGISTERED__');
});
