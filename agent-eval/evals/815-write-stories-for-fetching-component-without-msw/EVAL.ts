import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { describe, expect, test } from 'vitest';
import {
  expectDisplayReviewForVisualChange,
  expectReviewOpenedInBrowser,
  expectSkillInvoked,
  expectStoryDiscoveryBeforeReview,
  expectStoryIdsInDisplayReview,
  expectStoryTestsRanAndPassed,
  expectWorkflowCalls,
  getEvalContext,
  modelRunsTestsOnlyWhenAsked,
} from '#test-utils';

const STORIES_PATH = 'src/components/OrderHistory.stories.tsx';

describe('writing stories for a fetching OrderHistory in a project without MSW', () => {
  test('runs story tests after the change and finishes with them passing', async () => {
    await expectStoryTestsRanAndPassed({
      requireAgentRun: !modelRunsTestsOnlyWhenAsked(),
      covering: ['orderhistory'],
    });
  });

  test('installs MSW and its Storybook addon', () => {
    const { dependencies = {}, devDependencies = {} } = JSON.parse(
      readFileSync('package.json', 'utf8')
    );
    const installed = { ...dependencies, ...devDependencies };
    expect(installed, 'Expected msw to be installed').toHaveProperty('msw');
    expect(installed, 'Expected msw-storybook-addon to be installed').toHaveProperty(
      'msw-storybook-addon'
    );
    expect(
      existsSync('public/mockServiceWorker.js'),
      'Expected the worker script generated by `msw init`'
    ).toBe(true);
    const preview = readdirSync('.storybook').find((file) => file.startsWith('preview.'));
    expect(
      readFileSync(`.storybook/${preview}`, 'utf8'),
      'Expected the preview file to set up msw-storybook-addon'
    ).toMatch(/msw-storybook-addon/);
  });

  test('mocks the request with MSW instead of a module mock or a stubbed fetch', () => {
    const component = readFileSync('src/components/OrderHistory.tsx', 'utf8');
    expect(component, 'Expected OrderHistory to keep taking no props').toMatch(
      /export default function OrderHistory\s*\(\s*\)/
    );
    expect(component, 'Expected OrderHistory to keep fetching /api/orders').toMatch(
      /fetch\(\s*['"`]\/api\/orders/
    );

    expect(existsSync(STORIES_PATH), `Expected the stories in ${STORIES_PATH}`).toBe(true);
    const stories = readFileSync(STORIES_PATH, 'utf8');
    expect(stories, 'Expected handlers registered with msw.use').toMatch(/\bmsw\.use\(/);
    expect(stories, 'Expected the handlers to mock /api/orders').toMatch(/\/api\/orders/);
    expect(stories, 'Expected no module mock or stubbed fetch').not.toMatch(
      /\bsb\.mock\(|\bvi\.mock\(|\bmocked\(|\bspyOn\(|\b(globalThis|window)\.fetch\s*=/
    );
    expect(
      stories.match(/^export const \w+/gm)?.length ?? 0,
      'Expected loaded, empty, and error stories'
    ).toBeGreaterThanOrEqual(3);
  });

  test('uses Storybook story instructions and publishes a display review', () => {
    expectWorkflowCalls(['get-storybook-story-instructions', 'review-create']);
    expectDisplayReviewForVisualChange();
  });

  test('opens the review in the in-app browser', () => {
    expectReviewOpenedInBrowser();
  });

  test('the review covers the new OrderHistory stories', () => {
    expectStoryIdsInDisplayReview(['orderhistory']);
  });

  test('discovers stories through the workflow tools before publishing the review', () => {
    expectStoryDiscoveryBeforeReview();
  });

  test.skipIf(getEvalContext().integration === 'mcp')('invokes the stories skill', () => {
    expectSkillInvoked('stories');
  });
});
