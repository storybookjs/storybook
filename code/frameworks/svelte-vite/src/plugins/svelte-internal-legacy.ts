import { relative } from 'node:path';

import MagicString from 'magic-string';
import type { ImportDeclaration } from 'estree';
import { logger } from 'storybook/internal/node-logger';
import type { Plugin } from 'vite';

// `svelte/internal` in Svelte 5 is an export-less module that throws on evaluation: it was the
// private Svelte 4 runtime. Vite's dep optimizer marks it as needing interop, and the resulting
// interop rewrite requests the module's nonexistent `default` export. That link failure aborts
// evaluation of the preview graph's whole module tree, so one legacy component kills every story
// with an error that names no file.
//
// In dev this plugin rewrites imports of exactly `svelte/internal` to a virtual module whose
// default export is a stub that throws, naming the importing file and the accessed API, when a
// removed internal is used. The import links, clean stories keep working, and the failure degrades
// to the component's own import chain. Production builds keep the native missing-export failure,
// which already names the file. Only top-level import declarations are rewritten:
// `export { x } from 'svelte/internal'`, `export * from 'svelte/internal'` and dynamic
// `import('svelte/internal')` are not isolated and fail as they would without this plugin, with
// no warning.
//
// Migration shim for Svelte 4 → 5: Svelte 4-compiled dependencies still hand-write these imports
// and Svelte 5 passes them through compilation. Remove it when svelte-vite drops support for
// Svelte 4-compiled dependencies (the shim shipped in Storybook 11) or when best-effort legacy
// internals land in `svelte/internal`, tracked by https://github.com/sveltejs/svelte/issues/10359.

const LEGACY_SVELTE_INTERNAL_SOURCE = 'svelte/internal';
const VIRTUAL_PREFIX = 'virtual:svelte-internal-legacy';
const RESOLVED_VIRTUAL_PREFIX = `\0${VIRTUAL_PREFIX}`;

// Message text shared by every generated module; each module assembles it at runtime around the
// accessed target, so the same text backs the bare-import throw and every stub property.
const REMOVED_TEXT = `'svelte/internal' was a private module used by Svelte 4 components and no longer exists in Svelte 5.`;
const IMPORT_TRAILER = ` from 'svelte/internal'. This component fails to render until it is migrated to Svelte 5. 'storybook build' still fails on this file until it is migrated.`;
const ISOLATION_TEXT = `Storybook isolated the failure to this component's import chain — the rest of the preview keeps working. If you used 'svelte/internal' deliberately, raise your use case on https://github.com/sveltejs/svelte/issues.`;

function virtualImportId(importer: string, evaluate: boolean): string {
  const query = new URLSearchParams({ importer });
  if (evaluate) {
    query.set('evaluate', '1');
  }
  return `${VIRTUAL_PREFIX}?${query}`;
}

function generateVirtualModule(query: URLSearchParams): string {
  const importer = query.get('importer');
  if (!importer) {
    throw new Error(`The ${VIRTUAL_PREFIX} module requires an 'importer' query parameter.`);
  }

  const module = [
    `// Generated by @storybook/svelte-vite: legacy 'svelte/internal' guard`,
    `const message = (target) => [`,
    `  ${JSON.stringify(REMOVED_TEXT)},`,
    `  '',`,
    `  ${JSON.stringify(importer)} + ' imports ' + target + ${JSON.stringify(IMPORT_TRAILER)},`,
    `  '',`,
    `  ${JSON.stringify(ISOLATION_TEXT)},`,
    `].join('\\n');`,
  ];

  if (query.has('evaluate')) {
    // A bare side-effect import wanted the module evaluated: throw at evaluation, naming the file.
    module.push(`throw new Error(message('the module itself'));`);
  } else {
    // One shared stub for every binding: each property access returns a constructible function —
    // Svelte 4 output does `class C extends SvelteComponent`, so the class base must be
    // constructible — that throws naming the accessed API, so the module links and evaluates
    // cleanly and the failure waits for use. The target is a plain object, so a namespace binding
    // is not callable, like a real namespace object.
    module.push(
      `export default new Proxy({}, {`,
      `  get: (_, api) => function () {`,
      `    throw new Error(message("'" + String(api) + "'"));`,
      `  },`,
      `});`
    );
  }

  return module.join('\n');
}

export function svelteInternalLegacy(): Plugin {
  let projectRoot: string = process.cwd();
  const loggedImporters = new Set<string>();

  return {
    name: 'storybook:svelte-internal-legacy',
    apply: 'serve',
    config: () => ({
      // Keep the export-less Svelte 5 shim out of dep pre-bundling: pre-bundling it is what
      // produces the interop rewrite requesting its nonexistent default export. Returned, not
      // mutated: Vite deep-merges the hook's value with the user config and concatenates arrays.
      optimizeDeps: { exclude: [LEGACY_SVELTE_INTERNAL_SOURCE] },
    }),
    configResolved(resolvedConfig) {
      projectRoot = resolvedConfig.root;
    },
    resolveId: {
      order: 'pre',
      filter: { id: new RegExp(`^${VIRTUAL_PREFIX}`) },
      handler(source) {
        return `${RESOLVED_VIRTUAL_PREFIX}${source.slice(VIRTUAL_PREFIX.length)}`;
      },
    },
    load: {
      filter: { id: new RegExp(`^\\${RESOLVED_VIRTUAL_PREFIX}`) },
      handler(id) {
        return generateVirtualModule(new URLSearchParams(id.split('?')[1]));
      },
    },
    transform: {
      filter: {
        id: /\.(svelte|[cm]?[jt]sx?)($|\?)/,
        code: /['"]svelte\/internal['"]/,
      },
      handler(code, id) {
        const ast = this.parse(code);
        const legacyImports = ast.body.filter(
          (node): node is ImportDeclaration =>
            node.type === 'ImportDeclaration' && node.source.value === LEGACY_SVELTE_INTERNAL_SOURCE
        );
        if (legacyImports.length === 0) {
          return null;
        }

        const importerPath = id.split('?')[0];
        const relativeImporter = relative(projectRoot, importerPath) || importerPath;
        const magicString = new MagicString(code);

        for (const [index, importDeclaration] of legacyImports.entries()) {
          // Rollup AST nodes carry start/end offsets; the estree types omit them.
          const { start, end } = importDeclaration as ImportDeclaration & {
            start: number;
            end: number;
          };

          if (importDeclaration.specifiers.length === 0) {
            magicString.overwrite(
              start,
              end,
              `import '${virtualImportId(relativeImporter, true)}'`
            );
            continue;
          }

          const stubBinding = `__sbSvelteInternalLegacy${index}`;
          const bindings = importDeclaration.specifiers.map((specifier) => {
            if (specifier.type === 'ImportNamespaceSpecifier') {
              return `${specifier.local.name} = ${stubBinding}`;
            }
            const imported =
              specifier.type === 'ImportDefaultSpecifier'
                ? 'default'
                : specifier.imported.type === 'Identifier'
                  ? specifier.imported.name
                  : String(specifier.imported.value);
            return `{ ${JSON.stringify(imported)}: ${specifier.local.name} } = ${stubBinding}`;
          });
          magicString.overwrite(
            start,
            end,
            [
              `import ${stubBinding} from '${virtualImportId(relativeImporter, false)}'`,
              `const ${bindings.join(', ')};`,
            ].join('\n')
          );
        }

        if (!loggedImporters.has(importerPath)) {
          loggedImporters.add(importerPath);
          logger.warn(
            `Isolated a legacy 'svelte/internal' import in ${relativeImporter}: uses of the removed Svelte 4 internals will throw an error naming this file, and the rest of the preview keeps working. 'storybook build' still fails on this file until it is migrated.`
          );
        }

        return {
          code: magicString.toString(),
          map: magicString.generateMap({ hires: true, source: id }).toString(),
        };
      },
    },
  };
}
