import { createRequire } from 'node:module';
import { join } from 'node:path';

import { format } from 'oxfmt';
import { rolldown } from 'rolldown';
import { dedent } from 'ts-dedent';

import coreConfig from '../../../core/build-config.ts';
import uiConfig from '../../ui/build-config.ts';
import managerConfig from '../build-config.ts';

import type { BuildEntries } from '../../../../scripts/build/utils/entry-utils.ts';
import { writeGeneratedFile } from '../../../../scripts/build/utils/write-generated-file.ts';

const CODE_DIR = join(import.meta.dirname, '..', '..', '..');
const MANAGER_ROOT_DIR = join(CODE_DIR, 'lib', 'manager');

const LOWER_PACKAGES: Array<[name: string, dir: string, config: BuildEntries]> = [
  ['@storybook/core', join(CODE_DIR, 'core'), coreConfig],
  ['@storybook/ui', join(CODE_DIR, 'lib', 'ui'), uiConfig],
  ['@storybook/manager', MANAGER_ROOT_DIR, managerConfig],
];

/** The manager globals name `storybook/*` keys; the scan resolves them, and their owners, to source. */
const localAlias = Object.fromEntries(
  LOWER_PACKAGES.flatMap(([name, dir, config]) =>
    Object.values(config.entries).flatMap((entries) =>
      entries.flatMap(({ exportEntries = [], entryPoint }) =>
        // A root key would alias every subpath by prefix; the manager globals never name one.
        exportEntries
          .filter((entry) => entry !== '.')
          .flatMap((entry) => [
            [`storybook${entry.slice(1)}`, join(dir, entryPoint)],
            [`${name}${entry.slice(1)}`, join(dir, entryPoint)],
          ])
      )
    )
  )
);

async function generateExportsFile(): Promise<void> {
  const destination = join(MANAGER_ROOT_DIR, 'src', 'ui', 'globals', 'exports.ts');
  const require = createRequire(join(MANAGER_ROOT_DIR, 'package.json'));

  const { globalPackages } = await import('../src/ui/globals/globals.ts');

  const input: Record<string, string> = {};
  const virtualModules: Record<string, string> = {};

  for (const mod of globalPackages) {
    const key = mod.replace(/[/@]/g, '_');
    input[key] = `\0${key}`;
    virtualModules[`\0${key}`] = `export * from '${mod}'`;
  }

  const bundle = await rolldown({
    input,
    resolve: { alias: localAlias },
    platform: 'browser',
    logLevel: 'silent',
    plugins: [
      {
        name: 'virtual',
        resolveId(id) {
          if (id.startsWith('\0')) return id;
        },
        load(id) {
          if (virtualModules[id]) return virtualModules[id];
        },
      },
    ],
  });

  const { output } = await bundle.generate({ format: 'esm' });

  const data: Record<string, string[]> = {};

  for (const chunk of output) {
    if (chunk.type !== 'chunk' || !chunk.isEntry) continue;
    const mod = globalPackages.find((m: string) => m.replace(/[/@]/g, '_') === chunk.name);
    if (!mod) continue;

    let exports = chunk.exports.filter((e: string) => e !== 'default').sort();

    // CJS modules don't expose ESM exports — fall back to require()
    if (exports.length === 0) {
      try {
        exports = Object.keys(require(mod))
          .filter((k) => k !== 'default' && k !== '__esModule')
          .sort();
      } catch {
        // ignore — module may not be requireable
      }
    }

    data[mod] = exports;
  }

  // Preserve key order from globalsNameReferenceMap for deterministic output
  const ordered = Object.fromEntries(globalPackages.map((mod: string) => [mod, data[mod]]));

  const { code: formatted } = await format(
    'exports.ts',
    dedent`
      // this file is generated by sourcefiles.ts
      // this is done to prevent runtime dependencies from making it's way into the build/start script of the manager
      // the manager builder needs to know which dependencies are 'globalized' in the ui

      export default ${JSON.stringify(ordered)} as const;
    `,
    { singleQuote: true }
  );

  await writeGeneratedFile(destination, formatted);
}

generateExportsFile();
