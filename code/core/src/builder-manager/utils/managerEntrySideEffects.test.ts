import { mkdtemp, mkdir, rm, symlink, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';

import * as esbuild from 'esbuild';
import { join, normalize } from 'pathe';
import { describe, expect, it, onTestFinished } from 'vitest';

import {
  createInsideEntryPackageMatcher,
  findPackageRoot,
  preserveManagerEntrySideEffectsPlugin,
} from './managerEntrySideEffects.ts';

/*
 * Builds a fixture project shaped like a real manager entry setup: an addon package that declares
 * `"sideEffects": false` and registers its panel through an internal import one level below its
 * manager entry. A nested dependency under the addon's own node_modules and a side-effect-free
 * dependency (a @storybook/icons stand-in) must stay tree-shakable. The entry is imported through
 * a wrapper file, as generated by `wrapManagerEntries` (`import '<entry>';`).
 *
 * Assertions run against the emitted bundle text: `register.js` and the dependencies have no
 * exports, so their top-level `globalThis` assignments are the proof they survived tree-shaking.
 */
const createFixtureProject = async () => {
  const root = await mkdtemp(join(tmpdir(), 'sb-manager-entry-side-effects-'));
  onTestFinished(() => rm(root, { recursive: true, force: true }));

  const addonDir = join(root, 'node_modules', 'fixture-addon');
  const addonDistDir = join(addonDir, 'dist');
  await mkdir(addonDistDir, { recursive: true });
  await writeFile(
    join(addonDir, 'package.json'),
    JSON.stringify({
      name: 'fixture-addon',
      version: '1.0.0',
      type: 'module',
      sideEffects: false,
      exports: { '.': './dist/manager.js' },
    })
  );
  await writeFile(
    join(addonDistDir, 'manager.js'),
    "import './register.js';\nimport 'fixture-icons';\nimport 'nested-dep';\n"
  );
  await writeFile(
    join(addonDistDir, 'register.js'),
    'globalThis.__FIXTURE_PANEL_REGISTERED__ = true;\n'
  );

  const iconsDistDir = join(root, 'node_modules', 'fixture-icons', 'dist');
  await mkdir(iconsDistDir, { recursive: true });
  await writeFile(
    join(root, 'node_modules', 'fixture-icons', 'package.json'),
    JSON.stringify({
      name: 'fixture-icons',
      version: '1.0.0',
      type: 'module',
      sideEffects: false,
      main: './dist/index.js',
    })
  );
  await writeFile(
    join(iconsDistDir, 'index.js'),
    'globalThis.__FIXTURE_ICON_SIDE_EFFECT__ = true;\nexport const Icon = () => null;\n'
  );

  const nestedDepDir = join(addonDir, 'node_modules', 'nested-dep');
  await mkdir(nestedDepDir, { recursive: true });
  await writeFile(
    join(nestedDepDir, 'package.json'),
    JSON.stringify({
      name: 'nested-dep',
      version: '1.0.0',
      type: 'module',
      sideEffects: false,
      main: './index.js',
    })
  );
  await writeFile(join(nestedDepDir, 'index.js'), 'globalThis.__FIXTURE_NESTED_DEP__ = true;\n');

  return root;
};

const writeWrapper = async (dir: string, specifier: string) => {
  const wrapperPath = join(dir, 'wrapper.js');
  await mkdir(dir, { recursive: true });
  await writeFile(wrapperPath, `import '${specifier.replaceAll("'", "\\'")}';\n`);
  return wrapperPath;
};

const buildManagerBundle = async (root: string, wrapperPath: string, withPlugin: boolean) => {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: [wrapperPath],
    bundle: true,
    write: false,
    outdir: 'dist',
    platform: 'browser',
    format: 'iife',
    // Without the plugin, dropping the entry import emits `ignored-bare-import` warnings; keep
    // them out of the test output (real errors still fail the build).
    logLevel: 'silent',
    plugins: withPlugin ? [preserveManagerEntrySideEffectsPlugin([wrapperPath])] : [],
  });
  return result.outputFiles[0].text;
};

it('keeps the registration and tree-shakes dependencies for a bare-specifier entry', async () => {
  const root = await createFixtureProject();
  const wrapperPath = await writeWrapper(join(root, 'sb-addons'), 'fixture-addon');
  const bundle = await buildManagerBundle(root, wrapperPath, true);

  expect(bundle).toContain('__FIXTURE_PANEL_REGISTERED__');
  expect(bundle).not.toContain('__FIXTURE_ICON_SIDE_EFFECT__');
  expect(bundle).not.toContain('__FIXTURE_NESTED_DEP__');
});

it('keeps the registration when the entry is an absolute path', async () => {
  const root = await createFixtureProject();
  const managerPath = join(root, 'node_modules', 'fixture-addon', 'dist', 'manager.js');
  const wrapperPath = await writeWrapper(join(root, 'sb-addons'), managerPath);
  const bundle = await buildManagerBundle(root, wrapperPath, true);

  expect(bundle).toContain('__FIXTURE_PANEL_REGISTERED__');
});

it('keeps the registration when the wrapper is reached through a symlinked directory', async () => {
  const root = await createFixtureProject();
  // The Storybook cache dir can be a symlink (a linked node_modules, `/var` -> `/private/var` on
  // macOS, some Docker/Bazel layouts): esbuild reports the wrapper's real path, so the plugin must
  // canonicalize the wrapper paths it was given before comparing.
  const realDir = join(root, 'sb-addons-real');
  await writeWrapper(realDir, 'fixture-addon');
  await symlink(realDir, join(root, 'sb-addons'), 'dir');
  const bundle = await buildManagerBundle(root, join(root, 'sb-addons', 'wrapper.js'), true);

  expect(bundle).toContain('__FIXTURE_PANEL_REGISTERED__');
});

it('without the plugin, the entry import and its registration are dropped', async () => {
  const root = await createFixtureProject();
  const wrapperPath = await writeWrapper(join(root, 'sb-addons'), 'fixture-addon');
  const bundle = await buildManagerBundle(root, wrapperPath, false);

  expect(bundle).not.toContain('__FIXTURE_PANEL_REGISTERED__');
});

describe('findPackageRoot', () => {
  const createEmptyDir = async () => {
    const root = await mkdtemp(join(tmpdir(), 'sb-manager-entry-side-effects-'));
    onTestFinished(() => rm(root, { recursive: true, force: true }));
    return root;
  };

  it('walks past inner manifests without a name or sideEffects field', async () => {
    const root = await createEmptyDir();
    // Dual-format packages ship inner manifests like `dist/esm/package.json` that only carry
    // `{"type": "module"}`; the root that esbuild applies the annotation to is the package root.
    const packageRoot = join(root, 'node_modules', 'fixture-dual');
    await mkdir(join(packageRoot, 'dist', 'esm'), { recursive: true });
    await writeFile(
      join(packageRoot, 'dist', 'esm', 'package.json'),
      JSON.stringify({ type: 'module' })
    );
    await writeFile(
      join(packageRoot, 'package.json'),
      JSON.stringify({ name: 'fixture-dual', sideEffects: false })
    );

    expect(findPackageRoot(join(packageRoot, 'dist', 'esm', 'index.js'))).toBe(packageRoot);
  });

  it('stops at node_modules', async () => {
    const root = await createEmptyDir();
    const orphanDir = join(root, 'node_modules', 'orphan');
    await mkdir(orphanDir, { recursive: true });

    expect(findPackageRoot(join(orphanDir, 'index.js'))).toBeUndefined();
  });
});

describe('entry-package matching', () => {
  // Native Windows paths: esbuild reports them with backslashes in plugin callbacks, so the
  // matcher has to fold separators before comparing (path.win32 fixtures, run on every platform).
  const win32Root = 'C:\\storybook-cache\\node_modules\\fixture-addon';

  it('matches native windows paths against a normalized root', () => {
    const isInsideEntryPackage = createInsideEntryPackageMatcher([win32Root]);

    expect(
      isInsideEntryPackage('C:\\storybook-cache\\node_modules\\fixture-addon\\dist\\register.js')
    ).toBe(true);
    expect(isInsideEntryPackage(normalize('C:\\storybook-cache\\elsewhere\\index.js'))).toBe(false);
  });

  it('does not match modules under a nested node_modules', () => {
    const isInsideEntryPackage = createInsideEntryPackageMatcher([win32Root]);

    expect(
      isInsideEntryPackage(
        'C:\\storybook-cache\\node_modules\\fixture-addon\\node_modules\\nested-dep\\index.js'
      )
    ).toBe(false);
  });
});
