import { relative } from 'node:path';

import { MagicString } from 'magic-string';
import type { ImportDeclaration } from 'estree';
import { logger } from 'storybook/internal/node-logger';
import type { Plugin } from 'vite';

/**
 * Under Svelte 5, `svelte/internal` is an export-less module that throws on evaluation (it was the
 * private Svelte 4 runtime). Vite's dep optimizer marks such modules as needing interop (they have
 * no import/export syntax), which rewrites consumer imports into a request for the module's
 * `default` export. Since the module has no exports at all, that request fails to link, and because
 * the Storybook preview graph is statically linked, a single legacy component would kill every
 * story with an error that names no file.
 *
 * This plugin rewrites imports of exactly `svelte/internal` to a virtual module whose exports are
 * stubs that throw an error naming the importing file when used. The import links, the module
 * evaluates, and the failure degrades to the component's own import chain instead of the whole
 * preview graph. It intentionally does not make the legacy internals work — every use throws.
 */

/** The exact module specifier guarded by this plugin. Subpaths like `svelte/internal/client` are the real Svelte 5 runtime and are never touched. */
export const LEGACY_SVELTE_INTERNAL_SOURCE = 'svelte/internal';

const VIRTUAL_PREFIX = 'virtual:svelte-internal-legacy';
const RESOLVED_VIRTUAL_PREFIX = `\0${VIRTUAL_PREFIX}`;

type ImportMode = 'names' | 'proxy' | 'sideeffect';

function formatErrorMessage(importer: string, api?: string): string {
  const target = api ? `'${api}'` : `the module itself`;
  return [
    `'svelte/internal' was a private module used by Svelte 4 components and no longer exists in Svelte 5.`,
    ``,
    `${importer} imports ${target} from 'svelte/internal'. This component fails to render until it is migrated to Svelte 5.`,
    ``,
    `Storybook isolated the failure to this component's import chain — the rest of the preview keeps working. If you used 'svelte/internal' deliberately, raise your use case on https://github.com/sveltejs/svelte/issues.`,
  ].join('\n');
}

export function generateVirtualModule(query: URLSearchParams, importer: string): string {
  const throwLine = (api: string) =>
    `throw new Error(${JSON.stringify(formatErrorMessage(importer, api))});`;

  if (query.get('mode') === 'sideeffect') {
    // A bare side-effect import explicitly wanted the module evaluated: throw on evaluation,
    // mirroring the real Svelte 5 shim, but with the importing file in the message.
    return [
      `// Generated by @storybook/svelte-vite: legacy 'svelte/internal' guard`,
      throwLine(LEGACY_SVELTE_INTERNAL_SOURCE),
      '',
    ].join('\n');
  }

  if (query.get('mode') === 'proxy') {
    // Namespace access throws with the accessed property in the message.
    return [
      `// Generated by @storybook/svelte-vite: legacy 'svelte/internal' guard`,
      `const __sbLegacySvelteInternal = new Proxy(function () {}, { get: () => { ${throwLine(LEGACY_SVELTE_INTERNAL_SOURCE)} } });`,
      `export default __sbLegacySvelteInternal;`,
      '',
    ].join('\n');
  }

  const apis = (query.get('apis') ?? '').split(',').filter(Boolean);
  // Uniform stub + alias exports: `export { stub as name }` is valid for identifiers, string
  // names, and `default` alike. No top-level throw: the module must link and evaluate cleanly so
  // the failure stays local to the component that actually calls the removed API.
  return [
    `// Generated by @storybook/svelte-vite: legacy 'svelte/internal' guard`,
    ...apis.map(
      (api, index) => `const __sbLegacySvelteInternal${index} = () => { ${throwLine(api)} };`
    ),
    ...apis.map((api, index) => `export { __sbLegacySvelteInternal${index} as ${api} };`),
    '',
  ].join('\n');
}

function buildVirtualImport(mode: ImportMode, apis: string[], importer: string): string {
  const query = new URLSearchParams({ importer, mode });
  if (mode === 'names') {
    query.set('apis', apis.join(','));
  }
  return `'${VIRTUAL_PREFIX}?${query}'`;
}

export function svelteInternalLegacy(): Plugin {
  let command: string = 'serve';
  let projectRoot: string = process.cwd();
  const loggedImporters = new Set<string>();

  return {
    name: 'storybook:svelte-internal-legacy',
    config(config, { command: resolvedCommand }) {
      if (resolvedCommand === 'serve') {
        // Keep the export-less Svelte 5 shim out of dep pre-bundling so the optimizer never emits
        // an interop rewrite requesting its nonexistent default export. Dev-only: optimizeDeps does
        // not apply to production builds.
        config.optimizeDeps = {
          ...config.optimizeDeps,
          exclude: [...(config.optimizeDeps?.exclude ?? []), LEGACY_SVELTE_INTERNAL_SOURCE],
        };
      }
    },
    configResolved(resolvedConfig) {
      command = resolvedConfig.command;
      projectRoot = resolvedConfig.root;
    },
    resolveId: {
      order: 'pre',
      filter: { id: new RegExp(`^${VIRTUAL_PREFIX}`) },
      handler(source) {
        return `${RESOLVED_VIRTUAL_PREFIX}${source.slice(VIRTUAL_PREFIX.length)}`;
      },
    },
    load: {
      filter: { id: new RegExp(`^\\${RESOLVED_VIRTUAL_PREFIX}`) },
      handler(id) {
        const queryStart = id.indexOf('?');
        const query = new URLSearchParams(id.slice(queryStart + 1));
        const importer = query.get('importer') ?? '<unknown importer>';
        return generateVirtualModule(query, importer);
      },
    },
    transform: {
      filter: { id: /\.(svelte|jsx?|tsx?|mjs|cjs|cts|mts)($|\?)/ },
      handler(code, id) {
        // Production builds keep Vite/Rollup's native failure for missing exports, which names the
        // file: the loud build error is the behavior we want there.
        if (command !== 'serve') {
          return null;
        }

        // Extracted-CSS virtual modules (`Component.svelte?svelte&type=style&lang.css`) are not
        // JavaScript: parsing them would throw and fail the module load. Leave them untouched.
        if (id.includes('type=style') || id.endsWith('.css')) {
          return null;
        }

        // Fast path: a file whose code never mentions the source cannot import it. Skips the AST
        // parse for the overwhelming majority of modules.
        if (!code.includes(LEGACY_SVELTE_INTERNAL_SOURCE)) {
          return null;
        }

        const ast = this.parse(code);
        const legacyImports = ast.body.filter(
          (node): node is ImportDeclaration =>
            node.type === 'ImportDeclaration' && node.source.value === LEGACY_SVELTE_INTERNAL_SOURCE
        );
        if (legacyImports.length === 0) {
          return null;
        }

        const importerPath = id.split('?')[0];
        const relativeImporter = relative(projectRoot, importerPath) || importerPath;
        const magicString = new MagicString(code);

        for (const importDeclaration of legacyImports) {
          // acorn decorates every node with start/end offsets; the estree typings omit them.
          const { start, end } = importDeclaration as ImportDeclaration & {
            start: number;
            end: number;
          };
          const namespace = importDeclaration.specifiers.find(
            (specifier) => specifier.type === 'ImportNamespaceSpecifier'
          );
          if (namespace) {
            // `import * as ns from 'svelte/internal'` cannot mix with other specifier kinds in ESM.
            magicString.overwrite(
              start,
              end,
              `import { default as ${namespace.local.name} } from ${buildVirtualImport('proxy', [], relativeImporter)}`
            );
            continue;
          }

          if (importDeclaration.specifiers.length === 0) {
            // Bare side-effect import explicitly wanted the module evaluated.
            magicString.overwrite(
              start,
              end,
              `import ${buildVirtualImport('sideeffect', [], relativeImporter)}`
            );
            continue;
          }

          const apis: string[] = [];
          const bindings: string[] = [];
          for (const specifier of importDeclaration.specifiers) {
            if (specifier.type === 'ImportDefaultSpecifier') {
              apis.push('default');
              bindings.push(`default as ${specifier.local.name}`);
              continue;
            }
            if (specifier.type === 'ImportNamespaceSpecifier') {
              continue;
            }
            const imported =
              specifier.imported.type === 'Identifier'
                ? specifier.imported.name
                : String(specifier.imported.value);
            apis.push(imported);
            bindings.push(
              imported === specifier.local.name
                ? imported
                : `${imported} as ${specifier.local.name}`
            );
          }
          magicString.overwrite(
            start,
            end,
            `import { ${bindings.join(', ')} } from ${buildVirtualImport('names', apis, relativeImporter)}`
          );
        }

        if (!loggedImporters.has(id)) {
          loggedImporters.add(id);
          logger.info(
            `Isolated a legacy 'svelte/internal' import in ${relativeImporter}: uses of the removed Svelte 4 internals will throw an error naming this file, and the rest of the preview keeps working.`
          );
        }

        return {
          code: magicString.toString(),
          map: magicString
            .generateMap({ hires: true, source: id, includeContent: true })
            .toString(),
        };
      },
    },
  };
}
