import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { esMain } from './utils/esmain.ts';

import { type Template } from '../code/lib/cli-storybook/src/sandbox-templates.ts';
import * as templates from '../code/lib/cli-storybook/src/sandbox-templates.ts';

// @ts-expect-error somehow TS thinks there is a default export
const { allTemplates, daily, normal, docgenServerTemplates } = (templates.default ||
  templates) as typeof templates;

const skips = (template: Template, task: string) => template.skipTasks?.includes(task as never);

const CODE = join(import.meta.dirname, '../code');

// The Nx project of each workspace package under code/, by package name.
const projectsByPackage = new Map(
  ['', 'addons', 'builders', 'frameworks', 'lib', 'presets', 'renderers'].flatMap((group) =>
    readdirSync(join(CODE, group), { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => join(CODE, group, entry.name))
      .filter(
        (dir) => existsSync(join(dir, 'package.json')) && existsSync(join(dir, 'project.json'))
      )
      .map((dir) => [
        JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).name as string,
        JSON.parse(readFileSync(join(dir, 'project.json'), 'utf8')).name as string,
      ])
  )
);

// What every sandbox installs: `storybook` (core), the CLI that creates it, and the addons that
// `storybook init` adds.
const ALWAYS = ['core', 'cli', 'addon-a11y', 'addon-docs', 'addon-vitest', 'addon-onboarding'];

// The workspace packages a template's sandbox installs, as Nx projects: the sandbox's tasks are
// affected by a change to any of them (`nx affected`), and hash them (`^production`). Packages from
// npm, such as the community rsbuild frameworks, are no project; their renderer and builder from
// this repository still are.
export function sandboxDependencies(template: Template): string[] {
  const { framework, renderer, builder } = template.expected;
  const { extraDependencies = [], extraDevDependencies = [] } = template.modifications ?? {};
  const packages = [framework, renderer, builder, ...extraDependencies, ...extraDevDependencies];
  const projects = packages.flatMap((name) => projectsByPackage.get(name) ?? []);
  return [
    ...new Set([
      ...ALWAYS,
      ...projects,
      // The addon's E2E tests also run the MCP server of code/lib/mcp (addon-mcp.spec.ts).
      ...(projects.includes('addon-mcp') ? ['mcp'] : []),
    ]),
  ];
}

export const projectJson = (name: string, tags: string[], template: Template) => ({
  name,
  description: 'Do not edit. Auto generated by scripts/create-nx-sandbox-projects.ts.',
  projectType: 'application',
  implicitDependencies: sandboxDependencies(template),
  targets: {
    sandbox: {
      options: {
        // Ensure Nx sandboxes write to a stable, slash-free folder name
        // e.g. "react-vite/default-ts" -> "react-vite-default-ts"
        dir: name.replaceAll('/', '-'),
      },
    },
    dev: {},
    ...(template.typeCheck === true
      ? {
          'check-sandbox': {},
        }
      : {}),
    ...(template.skipTasks && template.skipTasks.includes('vitest-integration')
      ? {}
      : {
          'vitest-integration': {},
        }),
    build: {
      options: {
        dir: name.replaceAll('/', '-'),
      },
    },
    // The same tasks CircleCI runs for the template (scripts/ci/sandboxes.ts).
    ...(skips(template, 'chromatic') ? {} : { chromatic: {} }),
    // CircleCI's dev job smoke-tests the templates that skip the dev E2E tests.
    ...(skips(template, 'e2e-tests-dev') ? { 'smoke-test': {} } : {}),
    ...(docgenServerTemplates().includes(name as never) ? { 'docgen-baselines': {} } : {}),
    serve: {},
    ...(template.skipTasks && template.skipTasks.includes('e2e-tests')
      ? {}
      : {
          'e2e-tests': {},
        }),
    ...(template.skipTasks && template.skipTasks.includes('e2e-tests-dev')
      ? {}
      : {
          'e2e-tests-dev': {},
          // The two halves of e2e-tests-dev, which CI runs on different workers (nx.json).
          'e2e-tests-dev-1': {},
          'e2e-tests-dev-2': {},
        }),
  },
  tags,
});
// The project.json of every template's sandbox project, by its path from the repository root.
export function sandboxProjects(): Map<string, string> {
  return new Map(
    Object.entries(allTemplates).map(([key, value]) => {
      const tags = [
        ...(normal.includes(key as any) && !value.inDevelopment ? ['ci:normal'] : []),
        ...(daily.includes(key as any) && !value.inDevelopment ? ['ci:daily'] : []),
        // The sandbox CircleCI tests on Windows (`WINDOWS_TEMPLATE` in scripts/ci/nx/plan.ts).
        ...(key === daily[0] ? ['ci:windows'] : []),
      ];
      return [
        `code/sandbox/${key.replaceAll('/', '-')}/project.json`,
        `${JSON.stringify(projectJson(key, tags, value), null, 2)}\n`,
      ];
    })
  );
}

function ensureDirectoryExistence(filePath: string): void {
  const dir = dirname(filePath);
  if (existsSync(dir)) {
    return;
  }
  ensureDirectoryExistence(dir);
  mkdirSync(dir);
}

if (esMain(import.meta.url)) {
  for (const [path, data] of sandboxProjects()) {
    const full = join(CODE, '..', path);
    ensureDirectoryExistence(full);
    writeFileSync(full, data, { encoding: 'utf-8' });
    console.log(full);
  }
}
